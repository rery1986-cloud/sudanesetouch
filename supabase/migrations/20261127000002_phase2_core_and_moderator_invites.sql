  address text NOT NULL,
  notes text,
  total_price_sar numeric(12,2) NOT NULL CHECK (total_price_sar >= 0),
  commission_sar numeric(12,2) NOT NULL DEFAULT 0 CHECK (commission_sar >= 0),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'confirmed', 'completed', 'cancelled', 'rejected')),
  is_demo boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
