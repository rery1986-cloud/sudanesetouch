CREATE OR REPLACE FUNCTION public.create_moderator_invitation(
  p_email text, p_full_name text, p_phone_private text, p_country text,
  p_city text, p_region text, p_permissions jsonb, p_token_hash text
)
RETURNS TABLE (id uuid, expires_at timestamptz)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE new_id uuid;
BEGIN
  IF NOT public.is_platform_admin() THEN RAISE EXCEPTION 'not authorized'; END IF;
  IF coalesce(trim(p_email), '') = '' OR coalesce(trim(p_token_hash), '') = '' THEN RAISE EXCEPTION 'invalid invitation'; END IF;
  UPDATE public.moderator_invitations
  SET revoked_at = now()
  WHERE email_normalized = lower(trim(p_email)) AND used_at IS NULL AND revoked_at IS NULL;
  INSERT INTO public.moderator_invitations
    (email_normalized, full_name, phone_private, country, city, region, permissions, token_hash, created_by)
  VALUES
    (lower(trim(p_email)), trim(p_full_name), nullif(trim(p_phone_private), ''), trim(p_country), trim(p_city), trim(p_region), coalesce(p_permissions, '[]'::jsonb), trim(p_token_hash), (SELECT auth.uid()))
  RETURNING moderator_invitations.id, moderator_invitations.expires_at INTO new_id, expires_at;
  id := new_id;
  RETURN NEXT;
END;
$$;
REVOKE ALL ON FUNCTION public.create_moderator_invitation(text, text, text, text, text, text, jsonb, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_moderator_invitation(text, text, text, text, text, text, jsonb, text) TO authenticated;

CREATE OR REPLACE FUNCTION public.accept_moderator_invitation(p_token text)
RETURNS public.profiles
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE inv public.moderator_invitations;
DECLARE requester uuid := (SELECT auth.uid());
DECLARE token_digest text := encode(extensions.digest(convert_to(p_token, 'utf8'), 'sha256'), 'hex');
DECLARE updated_profile public.profiles;
BEGIN
  IF requester IS NULL THEN RAISE EXCEPTION 'authentication required'; END IF;
  SELECT * INTO inv FROM public.moderator_invitations
  WHERE token_hash = token_digest AND used_at IS NULL AND revoked_at IS NULL AND expires_at > now()
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'invalid or expired invitation'; END IF;
  IF lower(coalesce((SELECT auth.jwt() ->> 'email'), '')) <> inv.email_normalized THEN RAISE EXCEPTION 'invitation email mismatch'; END IF;
  UPDATE public.profiles
  SET role = 'moderator', full_name = inv.full_name, phone_private = coalesce(inv.phone_private, phone_private),
      country = inv.country, city = inv.city, region = inv.region, permissions = inv.permissions,
      is_active = true, updated_at = now()
  WHERE id = requester;
  IF NOT FOUND THEN RAISE EXCEPTION 'profile not found'; END IF;
  UPDATE public.moderator_invitations SET used_at = now(), auth_user_id = requester WHERE id = inv.id;
  SELECT * INTO updated_profile FROM public.profiles WHERE id = requester;
  RETURN updated_profile;
END;
$$;
REVOKE ALL ON FUNCTION public.accept_moderator_invitation(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.accept_moderator_invitation(text) TO authenticated;

