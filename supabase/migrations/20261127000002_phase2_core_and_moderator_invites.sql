-- Never let auth metadata change an existing role. Public sign-up can only create
-- the three public roles; moderator is granted only by accept_moderator_invitation().
CREATE OR REPLACE FUNCTION public.handle_new_public_profile()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  metadata jsonb := coalesce(NEW.raw_user_meta_data, '{}'::jsonb);
  requested_role text := metadata ->> 'role';
BEGIN
  IF TG_OP = 'INSERT' AND requested_role IN ('client', 'provider', 'merchant') THEN
    INSERT INTO public.profiles (
      id, role, full_name, phone_private, country, city, district, specialty, store_name
    ) VALUES (
      NEW.id,
      requested_role,
      coalesce(nullif(metadata ->> 'full_name', ''), 'مستخدم جديد'),
      coalesce(metadata ->> 'phone', ''),
      nullif(metadata ->> 'country', ''),
      nullif(metadata ->> 'city', ''),
      nullif(metadata ->> 'district', ''),
      nullif(metadata ->> 'specialty', ''),
      nullif(metadata ->> 'store_name', '')
    )
    ON CONFLICT (id) DO NOTHING;
  ELSIF TG_OP = 'UPDATE' THEN
    UPDATE public.profiles
    SET full_name = coalesce(nullif(metadata ->> 'full_name', ''), full_name),
        phone_private = coalesce(metadata ->> 'phone', phone_private),
        country = coalesce(nullif(metadata ->> 'country', ''), country),
        city = coalesce(nullif(metadata ->> 'city', ''), city),
        district = coalesce(nullif(metadata ->> 'district', ''), district),
        specialty = coalesce(nullif(metadata ->> 'specialty', ''), specialty),
        store_name = coalesce(nullif(metadata ->> 'store_name', ''), store_name),
        updated_at = now()
    WHERE id = NEW.id;
  END IF;
  RETURN NEW;
END;
$$;

